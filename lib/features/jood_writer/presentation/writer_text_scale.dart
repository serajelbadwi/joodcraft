import 'package:flutter/material.dart';

/// **المصدر الوحيد** لمقياس تكبير نصّ «جود كاتب».
///
/// كل المسارات تأخذ مقياسها من هنا ولا من غيره:
///
/// * لوحة التحرير — البناء، والشطر الآلي، والتمرير إلى الصفحة
///   (`writer_canvas.dart`) — تقرأه **مرّة واحدة عند البناء** فتثبّته وتمرّره
///   إلى كل مُقاساتها؛
/// * صفحات العرض/الطباعة (`writer_pages_view.dart`) تقرأه من هنا أيضاً.
///
/// لا يوجد مسار يمرّر مقياساً ثابتاً ولا يعتمد افتراضاً: العارضات (`Text`
/// و`TextField`) تأخذ المقياس **ضمناً** من `MediaQuery`، فكون الاشتقاق من
/// المنشأ ذاته يجعل **القياس = الرسم** حتماً — عدد الأسطر وارتفاعها المحسوبان
/// هما المرسومان بالضبط، على أيّ جهاز وبأيّ تكبير نظام. ولو اشتقّ مسار مقياسه
/// من مكان آخر (أو من افتراض `TextScaler.noScaling`) لقاس نصّاً أصغر ممّا
/// يُرسم فتغيّر التفاف الأسطر وفيضت الصفحة.
///
/// عند تغيّر مقياس النظام تُعاد بناء الودجات فيُعاد الاشتقاق تلقائياً —
/// فالمقياس **مثبَّت عند البناء** لا مطلقاً.
extension WriterTextScaleX on BuildContext {
  /// مقياس تكبير النص الفعّال في هذا الموضع من الشجرة — تكبير نظام التشغيل
  /// أو اليدوي — بالقيمة نفسها التي تُطبّقها الودجات على رسمها.
  TextScaler get writerTextScaler => MediaQuery.textScalerOf(this);
}
