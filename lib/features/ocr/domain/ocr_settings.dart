/// إعدادات الاستخراج — لغة، وضع تقطيع (PSM)، ومعالجة قبلية.
///
/// **لماذا إعدادات صريحة؟** لأن التقرير المقيس يثبت أن ضبط `psm` والتكبير
/// يغيّران الدقة أكثر من تغيير المحرّك: `psm 6` لصفحة نصّية متعددة الأسطر،
/// والتكبير ×1.5 وحده أضاف ‎+7.6 نقاط على أصعب صورة. فالمستخدم يحتاج أن
/// يجرّب بضغطة زر لا أن يعدّل كوداً.
library;

/// لغة التعرّف — تُترجم مباشرةً إلى وسيط `-l` في Tesseract.
enum OcrLanguage {
  /// العربية فقط.
  arabic('ara'),

  /// الإنجليزية فقط.
  english('eng'),

  /// الاثنان — يقرأ الأرقام والتواريخ الإنجليزية داخل نصّ عربي.
  both('ara+eng');

  const OcrLanguage(this.tesseractCode);

  /// الوسيط الذي يُمرَّر إلى `tesseract -l`.
  final String tesseractCode;
}

/// وضع تقطيع الصفحة (Page Segmentation Mode) — أهم مفتاح جودة عملي.
enum OcrPsm {
  /// تقسيم تلقائي كامل (افتراضي Tesseract) — يصلح لصفحة مختلطة.
  auto(3, 'تقسيم تلقائي'),

  /// كتلة نصّية واحدة متعددة الأسطر — الأنسب لبطاقة/شهادة واحدة.
  singleBlock(6, 'كتلة نصّية واحدة'),

  /// سطر واحد — يصلح لعنوان أو رمز.
  singleLine(7, 'سطر واحد'),

  /// نص متفرّق (جدول/بطاقات متعددة).
  sparseText(11, 'نص متفرّق');

  const OcrPsm(this.value, this.labelAr);

  /// القيمة التي تُمرَّر إلى `--psm`.
  final int value;

  /// اسم عربي للعرض في الواجهة.
  final String labelAr;
}

/// إعدادات استخراج واحدة.
///
/// **القيم الافتراضية هي ناتج قياس لا اجتهاد:** راجع
/// `report/ocr_improvement.md`. الافتراضي القديم (لغة `ara+eng`، PSM 6، بلا
/// عتبة) أعطى على نصّ عربي إسلامي نتائج يملك فيها النصّ اللاتيني الوهمي
/// (`ABN`، `gle`، `BI`) محلّ كلمات عربية. القياس يقول: اللغة العربية وحدها
/// حينها أدقّ، لأنّ نموذج `eng` يُنتج مرشّحات لاتينية لِأشكال عربية.
class OcrSettings {
  /// القيم الافتراضية **منتقاة بالقياس على ‎10‎ صور** بثلاث درجات صعوبة
  /// (`test/features/ocr_benchmark_10_images_test.dart`) — لا برأي ولا بقاعدة
  /// عامة. جدول المصفوفة الكامل في `report/ocr_improvement_v2.md`.
  ///
  /// **ما قاسه الاختبار على نصّ عربي إسلامي** (متوسط CER، الأقلّ خيرًا):
  ///
  /// | التركيبة | CER |
  /// |----------|-----|
  /// | تكبير ×1.5 + رمادي + تباين | **43.81%** ← الافتراضي |
  /// | تكبير + رمادي | 44.62% |
  /// | تكبير + رمادي + عتبة | 50.04% |
  /// | **كلّ المراحل معاً** (الافتراضي السابق) | **54.28%** ← الأسوأ |
  ///
  /// **ثلاث استنتاجات مقيسة تُبطل افتراضات شائعة:**
  ///
  /// 1. **عتبة Otsu تُضرّ** (+‎5.4‎ نقطة): تحوّل تدرّج الحبر الرمادي إلى
  ///    حافّة صلبة فتفقد Tesseract معلومة الظلّ التي يميّز بها الحرف.
  /// 2. **إزالة الضوضاء (متوسّط) تُضرّ** (+‎5.9‎ نقطة): المرشّح المتوسّط
  ///    يأكل الحواف الدقيقة بعد التكبير — وهذه وحدها ما يصنع الحرف العربي
  ///    المتّصل، فالنتيجة حروف مذابة لا كتل ضوضاء منفصلة.
  /// 3. **الميل لا حاجة له**: Tesseract يصحّح الميل داخلياً في PSM 3،
  ///    ومُصحّحنا أضاف ‎0.16‎ نقطة فرقاً لا يدفع ثمن زمنه.
  ///
  /// وأمّا التباين (`normalize` — تمديد المدى على ‎0..255‎) فيُبقي: رفع
  /// ‎0.8‎ نقطة مع بقاء الحافّة الرمادية التي يفقدها Otsu.
  const OcrSettings({
    this.language = OcrLanguage.arabic,
    this.psm = OcrPsm.auto,
    this.scale = 1.5,
    this.grayscale = true,
    this.binarize = false,
    this.denoise = false,
    this.deskew = false,
    this.multiPass = true,
    this.contrast = true,
  });

  /// اللغة المطلوبة (الافتراضي: عربي + إنجليزي).
  final OcrLanguage language;

  /// وضع التقطيع (الافتراضي: كتلة واحدة — الأنسب لمستندات JoodCraft).
  final OcrPsm psm;

  /// معامل التكبير قبل الاستخراج (1.0–3.0). Tesseract يعمل أحسن ما يكون على
  /// نصّ بمدى ~300dpi، وصورة الجوال العادية أقلّ من ذلك.
  final double scale;

  /// تحويل إلى رمادي أولاً (يُبسّط البينايرة ويُنظّف التشويش اللوني).
  final bool grayscale;

  /// ⚠️ **الافتراضي مطفأ بالقياس لا باليقين.** العتبة الصريحة خسرت ‎5.4‎
  /// نقطة على مجموعة الصور العشرة: تحوّل الحبر الرمادي إلى حافّة صلبة
  /// فتفقد Tesseract معلومة الظلّ التي تُميّز بها الحرف العربي المتّصل.
  /// تبقى متاحة لمن يريدها على ورقٍ مصوّر عالي التباين.
  final bool binarize;

  /// إزالة الضوضاء ذات النقطة الواحدة (مرشّح متوسّط على البكسلات).
  ///
  /// ⚠️ **الافتراضي مطفأ بالقياس.** المرشّح المتوسّط خسر ‎5.9‎ نقطة: يأكل
  /// الحواف الدقيقة بعد التكبير، وهذه الحواف وحدها ما يصنع الحروف العربية
  /// المتّصلة — فالناتج حروفٌ مذابة لا كتل ضوضاء منفصلة.
  final bool denoise;

  /// رفع التباين بمدّ القيم على كامل المدى (0..255) قبل العتبة.
  ///
  /// 🔆 **مفعّل افتراضياً:** يرفع ‎0.8‎ نقطة في قياس المصفوفة، وينقذ الصور
  /// الباهتة (حبر خفيف أو ظلّ أو كاميرا قديمة تجمع النصّ في شريحة رمادية
  /// ضيّقة). وخلافاً للعتبة الصريحة يمدّ المدى **دون** تسطيب الحافّات،
  /// فيبقى ما يبني عليه Tesseract تشكيل الحرف.
  final bool contrast;

  /// تصحيح الميل بالملف الإسقاطي (projection profile).
  ///
  /// 📐 **الافتراضي مطفأ.** القياس لا برأي: Tesseract يصحّح الميل داخلياً
  /// في PSM 3، ومُصحّحنا أضاف ‎0.16‎ نقطة فقط — لا يدفع ثمن زمنه ولا
  /// خطر تدويرٍ على صورةٍ سليمة. يبقى متاحاً لمن يرى صوره مائلة فعلاً.
  final bool deskew;

  /// تشغيل عدّة مرورات بأوضاع تقطيع مختلفة واختيار الأفضل.
  ///
  /// 🔁 **الافتراضي مفعّل، والزمن محفوظ:** الوضع المطلوب أوّلاً، وإن كانت
  /// نتيجته **جديدة كافية** (ثقة ‎≥ 80%‎ و‎3‎ كلمات فأكثر) يُقبل فوراً
  /// بمرور واحد. البدائل (‎PSM 3/4/6‎) لا تُشغَّل إلاّ عند الضعف — فالصورة
  /// الجيدة تبقى سريعة (مرور واحد)، والصعبة وحدها تدفع ثمناً.
  final bool multiPass;

  /// حدود آمنة للتكبير في الواجهة.
  static const double minScale = 1.0;
  static const double maxScale = 3.0;

  /// حدّ إثارة تصحيح الميل (درجات). الميلان الطبيعي للمسح الضوئي أقلّ من
  /// ذلك وعادةً يكون داخل احتمال أخطاء القياس نفسه — والتدوير عندها يُضيف
  /// ضبابية بلا فائدة.
  static const double deskewThreshold = 0.4;

  /// أقصى ميل يُصحَّح (درجات) — ما زاد يُعتبر صورةً قُطعت أو مُدارة عمداً.
  static const double maxDeskewDegrees = 12.0;

  OcrSettings copyWith({
    OcrLanguage? language,
    OcrPsm? psm,
    double? scale,
    bool? grayscale,
    bool? binarize,
    bool? denoise,
    bool? deskew,
    bool? multiPass,
    bool? contrast,
  }) {
    return OcrSettings(
      language: language ?? this.language,
      psm: psm ?? this.psm,
      scale: scale ?? this.scale,
      grayscale: grayscale ?? this.grayscale,
      binarize: binarize ?? this.binarize,
      denoise: denoise ?? this.denoise,
      deskew: deskew ?? this.deskew,
      multiPass: multiPass ?? this.multiPass,
      contrast: contrast ?? this.contrast,
    );
  }

  /// هل المعالجة قبلية مطلوبة فعلاً؟ (بلا معالجة = نسخ البايتات كما هي).
  ///
  /// ⚠️ `contrast` كان غائباً عن هذه القائمة: لو أطفأ المستخدم كلّ ما عداه
  /// لبقي التباين وحده ثم يُسقط الاختبار المعالجة كلّها فلا يُطبَّق أصلاً.
  bool get needsPreprocessing =>
      scale != 1.0 || grayscale || binarize || denoise || deskew || contrast;
}
