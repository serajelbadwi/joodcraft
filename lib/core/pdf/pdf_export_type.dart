/// نوع تصدير ملف PDF — يحدّد **محرّك الرسم** الذي يبني الملف النهائي.
///
/// وُضع في `core/pdf` (لا في ودجت المعاينة) لأن طبقتيّ الخدمة والواجهة
/// تحتاجانه معاً: الخدمة تقبله لتبني بالمحرّك المطلوب، والمعاينة تعرضه في
/// حوار «نوع التصدير». لو بقي في ملف الودجت لأدّى استيراد الخدمة لودجت إلى
/// دورة (ودجت ← خدمة ← ودجت).
enum PdfExportType {
  /// صور نقطية (Raster): صورة كاملة لكل صفحة، مطابقة للمحرّر 100%، وحجمها
  /// أكبر، والنص فيها جزء من الصورة فلا يُنسَخ ولا يُبحث عنه.
  images,

  /// فيكتور (Vector): النصّ مضمّن كمحارف حقيقية فيتسرّب ويُبحث، والأشكال
  /// أوامر مسار، فحجم الملف أصغر عادةً.
  vector,
}
