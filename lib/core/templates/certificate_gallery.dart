  static TemplateDocument _doc(
    List<TemplateElement> elements, {
    String background = '#FFFFFF',
    BackgroundGradient? gradient,
  }) =>
      TemplateDocument(
        elements: elements,
        paperSize: PaperSize.a4,
        orientation: PageOrientation.landscape,
        backgroundHex: background,
        backgroundGradient: gradient,
        sampleData: _sample,
      );

  static ElementBox _b(double x, double y, double w, double h) =>
      ElementBox(x: x, y: y, width: w, height: h);

  static ShapeElement _rect(
    String id,
    double x,
    double y,
    double w,
    double h, {
    String? fill,
    String? stroke,
    double strokeWidth = 0,
    double radius = 0,
    List<double>? corners,
    ShapeGradient? gradient,
    ShapeShadow? shadow,
    double fillOpacity = 1,
    double opacity = 1,
  }) =>
      ShapeElement(
        id: id,
        box: _b(x, y, w, h),
        kind: ShapeKind.rect,
        fillHex: fill,
        strokeHex: stroke,
        strokeWidth: strokeWidth,
        radius: radius,
        cornerRadii: corners,
        gradient: gradient,
        shadow: shadow,
        fillOpacity: fillOpacity,
        opacity: opacity,
      );

  static ShapeElement _ellipse(
    String id,
    double x,
    double y,
    double w,
    double h, {
    String? fill,
    String? stroke,
    double strokeWidth = 0,
    double opacity = 1,
  }) =>
      ShapeElement(
        id: id,
        box: _b(x, y, w, h),
        kind: ShapeKind.ellipse,
        fillHex: fill,
        strokeHex: stroke,
        strokeWidth: strokeWidth,
        opacity: opacity,
      );

  static ShapeElement _star(
    String id,
    double x,
    double y,
    double side, {
    String fill = '#C9A227',
    int points = 5,
    double opacity = 1,
  }) =>
      ShapeElement(
        id: id,
        box: _b(x, y, side, side),
        kind: ShapeKind.star,
        fillHex: fill,
        points: points,
        innerRadius: 0.45,
        opacity: opacity,
      );

  static ShapeElement _line(
    String id,
    double x,
    double y,
    double w, {
    required String stroke,
    double strokeWidth = 1,
    List<double>? dash,
  }) =>
      ShapeElement(
        id: id,
        box: _b(x, y, w, 0),
        kind: ShapeKind.line,
        strokeHex: stroke,
        strokeWidth: strokeWidth,
        dashPattern: dash,
      );

  static TextElement _text(
    String id,
    double x,
    double y,
    double w,
    double h,
    String text, {
    double size = 16,
    String color = '#1B2539',
    PdfFontWeight weight = PdfFontWeight.regular,
    PdfFontFamily family = PdfFontFamily.plex,
    ElementTextAlign align = ElementTextAlign.center,
    ElementVerticalAlign valign = ElementVerticalAlign.top,
    double lineHeight = 1.4,
    int? maxLines,
    double letterSpacing = 0,
    ElementDirection direction = ElementDirection.rtl,
  }) =>
      TextElement(
        id: id,
        box: _b(x, y, w, h),
        text: text,
        family: family,
        weight: weight,
        fontSize: size,
        colorHex: color,
        align: align,
        verticalAlign: valign,
        direction: direction,
        lineHeight: lineHeight,
        letterSpacing: letterSpacing,
        maxLines: maxLines,
      );

  static SealElement _seal(
    String id,
    double x,
    double y,
    double side, {
    String fill = '#C9A227',
    String ring = '#FFFFFF',
